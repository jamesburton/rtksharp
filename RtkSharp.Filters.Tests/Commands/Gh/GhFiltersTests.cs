    public void Truncate_MultibyteCountsRunes()
    {
        Assert.Equal("🚀🎉🔥abc", GhFilters.Truncate("🚀🎉🔥abc", 6)); // exact fit
        Assert.Equal("🚀🎉🔥ab...", GhFilters.Truncate("🚀🎉🔥abcdef", 8)); // truncated on rune boundary
    }

