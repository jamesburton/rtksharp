using System.Text.Json;
using RtkSharp.Filters.Commands.Gh;

namespace RtkSharp.Filters.Tests.Commands.Gh;

/// <summary>
/// Tests for <see cref="GhFilters"/>. The JSON-formatting and markdown-filtering helpers are pure
/// functions ported from <c>src/cmds/git/gh_cmd.rs</c>, so most of this suite exercises them directly
/// with the same inline JSON shapes the Rust module's own tests use. Moved from
/// <c>RtkSharp.Tests.Commands.GhCommandTests</c> when the underlying pure methods moved from
/// <c>RtkSharp.Commands.Gh.GhCommand</c> to <see cref="GhFilters"/> (Task 5 of the filters-library
/// extraction). Argument-parsing helpers (<c>HasJsonFlag</c>, <c>ExtractIdentifierAndExtraArgs</c>,
/// <c>ParseOptionalIdentifier</c>, the <c>ShouldPassthrough*</c> guards, <c>HasNonDiffFormatFlag</c>,
/// <c>PrStatusJsonFields</c>) and dispatch tests were not moved — they remain in the original
/// <c>GhCommandTests</c> alongside <c>GhCommand</c>. The format expectations are oracle-derived: <c>gh
/// pr view</c>/<c>pr list</c>/<c>issue list</c> were confirmed byte-identical against the reference
/// <c>rtk.exe</c> for the equivalent live invocations against this repository's GitHub remote.
/// </summary>
public sealed class GhFiltersTests
{
