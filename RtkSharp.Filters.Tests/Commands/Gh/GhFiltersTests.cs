    public void Truncate_LongGetsEllipsis() =>
        Assert.Equal("this is a ve...", GhFilters.Truncate("this is a very long string", 15));

    [Fact]
    public void Truncate_MaxLenBelowThree() => Assert.Equal("...", GhFilters.Truncate("abcdef", 2));

